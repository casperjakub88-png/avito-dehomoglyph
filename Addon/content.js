// ============================================================================
//  content.js — выполняется на страницах Avito в ИЗОЛИРОВАННОМ мире расширения
//  (скрипты самой страницы Avito в этот контекст и в его канал к фону доступа
//  НЕ имеют). Команды в фон идут через browser.runtime — это закрытый канал.
//
//  ВАЖНО про безопасность: здесь НЕТ приёма команд через window.postMessage от
//  страницы. Если в будущем понадобится принимать запросы от внешнего
//  userscript'а — это отдельный канал с проверкой, а не открытый postMessage,
//  иначе любой скрипт сайта сможет гонять твою модель (см. обсуждение).
//
//  Пока это точка интеграции (шаг Б): тут будет жить нормализация гомоглифов,
//  сбор «остатка» неоднозначных токенов с контекстом (заголовок объявления +
//  предложение) и применение вердиктов. Сейчас — каркас.
// ============================================================================
const api = (typeof browser !== "undefined") ? browser : chrome;

// Пример того, как контент-скрипт будет обращаться к фоновой модели.
// (Вызов отсюда — безопасный, идёт по внутреннему каналу расширения.)
async function adjudicateTokens(items) {
  const r = await api.runtime.sendMessage({ cmd: "adjudicate", items });
  if (!r || !r.ok) { console.warn("[content] адъюдикация не удалась:", r && r.error); return []; }
  return r.results; // [{token, context, script, raw}]
}

// Заглушка интеграции: на шаге Б здесь будет
//   1) запуск эвристики-нормализации по DOM объявления,
//   2) сбор оставшихся неоднозначных токенов + контекст (title + предложение),
//   3) adjudicateTokens(остаток) → применение вердиктов к тексту.
// Сейчас просто помечаем, что контент-скрипт жив.
console.log("[content] LLM-адъюдикатор: контент-скрипт активен на", location.host,
            "— ожидает интеграции нормализации (шаг Б).");

// чтобы линтеры/сборщики не ругались на неиспользуемую функцию-каркас:
window.__avitoLLMBridge = { adjudicateTokens };
